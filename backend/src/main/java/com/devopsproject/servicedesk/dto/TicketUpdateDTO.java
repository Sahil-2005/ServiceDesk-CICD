package com.devopsproject.servicedesk.dto;

import com.devopsproject.servicedesk.model.TicketPriority;
import jakarta.validation.constraints.NotBlank;

/**
 * DTO for updating ticket details via PUT /api/tickets/{id}.
 * Status is intentionally excluded — status changes must go through
 * the dedicated PATCH /api/tickets/{id}/status endpoint.
 */
public class TicketUpdateDTO {

    @NotBlank(message = "Title is required")
    private String title;

    @NotBlank(message = "Description is required")
    private String description;

    @NotBlank(message = "Category is required")
    private String category;

    private TicketPriority priority;

    private Long assignedTo;

    private String resolutionNotes;

    // Getters and Setters

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public TicketPriority getPriority() {
        return priority;
    }

    public void setPriority(TicketPriority priority) {
        this.priority = priority;
    }

    public Long getAssignedTo() {
        return assignedTo;
    }

    public void setAssignedTo(Long assignedTo) {
        this.assignedTo = assignedTo;
    }

    public String getResolutionNotes() {
        return resolutionNotes;
    }

    public void setResolutionNotes(String resolutionNotes) {
        this.resolutionNotes = resolutionNotes;
    }
}
